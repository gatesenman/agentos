package api

import "encoding/json"

// ProtocolVersion of the server<->node control channel. Bump on breaking change.
const ProtocolVersion = 1

// Endpoint paths used by nodes (see docs/protocol.md).
const (
	PathNodeConnect = "/api/v1/node/connect" // control WebSocket (JSON text frames)
	PathNodeTunnel  = "/api/v1/node/tunnel/" // + {session_id}; data WebSocket
	NodeTokenHeader = "Authorization"        // "Bearer <node token>"
)

// Envelope wraps every control message (one JSON object per WS text frame).
//
//	request : {"type":"agent.start","id":"r12","payload":{...}}
//	response: {"type":"response","reply_to":"r12","payload":{...}} or with "error"
//	event   : {"type":"agent.status","payload":{...}} (no id, no reply expected)
type Envelope struct {
	Type    string          `json:"type"`
	ID      string          `json:"id,omitempty"`
	ReplyTo string          `json:"reply_to,omitempty"`
	Error   string          `json:"error,omitempty"`
	Payload json.RawMessage `json:"payload,omitempty"`
}

// Message types.
const (
	// node -> server (first frame after connect)
	MsgHello = "hello" // HelloPayload
	// server -> node (reply to hello)
	MsgWelcome = "welcome" // WelcomePayload

	// server -> node requests (node MUST reply with MsgResponse)
	MsgAgentSync    = "agent.sync"    // SyncPayload -> response payload: null
	MsgAgentApply   = "agent.apply"   // AgentSpec   -> AgentStatus
	MsgAgentRemove  = "agent.remove"  // AgentRef    -> null
	MsgAgentStart   = "agent.start"   // AgentRef    -> AgentStatus
	MsgAgentStop    = "agent.stop"    // AgentRef    -> AgentStatus
	MsgAgentRestart = "agent.restart" // AgentRef    -> AgentStatus
	MsgAgentLogs    = "agent.logs"    // LogsRequest -> LogsResponse
	MsgTunnelOpen   = "tunnel.open"   // TunnelOpen  -> null (node then dials PathNodeTunnel+session)

	// node -> server events (no reply)
	MsgEvAgentStatus = "agent.status" // AgentStatus
	MsgEvAgentLog    = "agent.log"    // LogBatch
	MsgEvNodeStats   = "node.stats"   // NodeStats

	MsgResponse = "response"
)

type HelloPayload struct {
	ProtocolVersion int           `json:"protocol_version"`
	NodeID          string        `json:"node_id"` // stable, generated by node on first run
	Name            string        `json:"name"`
	Hostname        string        `json:"hostname"`
	OS              string        `json:"os"`
	Arch            string        `json:"arch"`
	Version         string        `json:"version"`
	Capabilities    []string      `json:"capabilities"`
	Agents          []AgentStatus `json:"agents"` // current runtime state of known agents
}

type WelcomePayload struct {
	NodeID        string `json:"node_id"`
	ServerVersion string `json:"server_version"`
}

// SyncPayload is the full desired set of agents for the node. Agents the node
// knows that are absent here must be stopped and removed (workspace kept).
type SyncPayload struct {
	Agents []AgentSpec `json:"agents"`
}

type AgentRef struct {
	ID string `json:"id"`
}

type LogsRequest struct {
	ID    string `json:"id"`
	Tail  int    `json:"tail"`            // max lines, default 200
	Since uint64 `json:"since,omitempty"` // only lines with Seq > Since
}

type LogsResponse struct {
	Lines []LogLine `json:"lines"`
}

type LogBatch struct {
	AgentID string    `json:"agent_id"`
	Lines   []LogLine `json:"lines"`
}

type NodeStats struct {
	NodeID string               `json:"node_id"`
	Host   HostStats            `json:"host"`
	Agents map[string]ProcStats `json:"agents"` // by agent id (running agents only)
}

// Tunnel kinds.
const (
	TunnelVNC    = "vnc"    // raw RFB bytes as binary WS frames (noVNC compatible)
	TunnelScreen = "screen" // built-in screen stream protocol (docs/protocol.md §5)
)

type TunnelOpen struct {
	SessionID string            `json:"session_id"`
	Kind      string            `json:"kind"`
	Params    map[string]string `json:"params,omitempty"` // e.g. vnc "addr", screen "quality","fps","display"
}

// ---- Phase 2 additions (backwards compatible; ProtocolVersion stays 1) ----
//
// Nodes that support them advertise CapExec / CapFiles in hello.capabilities.
// Exec and file transfer reuse the tunnel mechanism (tunnel.open + node dials
// PathNodeTunnel+session) with these kinds; directory listing is a control
// request. See docs/protocol.md §6.
const (
	CapExec  = "exec"  // node supports TunnelExec
	CapFiles = "files" // node supports TunnelFileGet/TunnelFilePut + MsgFsList

	// TunnelExec params: "cmd" (JSON array, required), "env" (JSON object),
	// "cwd", "tty" ("1"), "cols", "rows". Framing = /envs/{id}/exec WebSocket:
	// node->server binary = output, text {"type":"exit","code":N} | {"type":"error","message"};
	// server->node binary = stdin, text {"type":"resize","cols","rows"} | {"type":"eof"} (close stdin).
	TunnelExec = "exec"
	// TunnelFileGet params: "path". node->server: text {"type":"info","size":N,"mode":M}, binary chunks,
	// then text {"type":"eof"}; or text {"type":"error","message"}.
	TunnelFileGet = "file.get"
	// TunnelFilePut params: "path", "mode" (octal, default 0644). server->node: binary chunks then
	// text {"type":"eof"}; node->server: text {"type":"ok","size":N} | {"type":"error","message"}.
	TunnelFilePut = "file.put"

	MsgFsList = "fs.list" // FsListRequest -> FsListResponse
)

// Relative paths in exec cwd and file operations are resolved against the
// node's home directory (<node-data>/home); absolute paths are used as is.
type FsListRequest struct {
	Path string `json:"path"`
}

type FsEntry struct {
	Name    string `json:"name"`
	Size    int64  `json:"size"`
	Dir     bool   `json:"dir"`
	Mode    uint32 `json:"mode"`
	ModTime int64  `json:"mod_time"` // unix ms
}

type FsListResponse struct {
	Path    string    `json:"path"` // absolute, cleaned
	Entries []FsEntry `json:"entries"`
}
